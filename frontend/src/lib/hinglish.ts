const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
let compiled: Array<{ re: RegExp; out: string }> | null = null;

/** Hinglish for an English UI string, or undefined when there is none (caller falls back to English). */
export function toHinglish(en: string): string | undefined {
  const hit = PLAIN[en];
  if (hit !== undefined) return hit;
  // Longest template first, so "This session: {}/{} correct" wins over "{}/{} correct"
  compiled ??= Object.entries(TEMPLATES).sort((a, b) => b[0].length - a[0].length).map(([k, out]) => ({ re: new RegExp(`^${k.split('{}').map(escape).join('(.*?)')}$`, 's'), out }));
  for (const { re, out } of compiled) {
    const m = re.exec(en);
    if (m) {
      let i = 1;
      return out.replace(/\{\}/g, () => m[i++] ?? '');
    }
  }
  return undefined;
}
